<?php
/**
 * Where posts written on the site are kept, and how they are read and written.
 *
 * Posts are JSON files in storage/posts/. That folder is blocked from the web (.htaccess) and is
 * never produced by `node tools/build.mjs`, so uploading the site from a PC cannot delete a post.
 * The 14 original guides stay exactly as they are: static files built from src/blog/.
 */
class Store
{
    private static ?array $manifest = null;

    public static function root(): string
    {
        return dirname(__DIR__, 2);
    }

    public static function postsDir(): string
    {
        return self::root() . '/storage/posts';
    }

    public static function stateDir(): string
    {
        return self::root() . '/storage/cms';
    }

    /** Guides, categories and site details, written by tools/build.mjs. */
    public static function manifest(): array
    {
        if (self::$manifest === null) {
            $raw  = @file_get_contents(self::root() . '/src/generated/manifest.json');
            $data = $raw === false ? null : json_decode($raw, true);
            self::$manifest = is_array($data) ? $data : [];
        }
        return self::$manifest;
    }

    public static function site(string $key, string $fallback = ''): string
    {
        return (string) (self::manifest()['site'][$key] ?? $fallback);
    }

    public static function categories(): array
    {
        return self::manifest()['categories'] ?? [];
    }

    public static function guides(): array
    {
        return self::manifest()['guides'] ?? [];
    }

    public static function tintFor(string $category): string
    {
        foreach (self::categories() as $c) {
            if (($c['name'] ?? '') === $category) return (string) $c['tint'];
        }
        return 'tint-brand';
    }

    public static function categorySlug(string $category): string
    {
        foreach (self::categories() as $c) {
            if (($c['name'] ?? '') === $category) return (string) $c['slug'];
        }
        return self::slugify($category);
    }

    /** The page shell and card markup generated by the build, so posts match the site's design. */
    public static function shell(): string
    {
        return (string) @file_get_contents(self::root() . '/src/generated/post-shell.html');
    }

    public static function cardTemplate(): string
    {
        return (string) @file_get_contents(self::root() . '/src/generated/post-card.html');
    }

    /** Posts written on the site, newest first. */
    public static function all(bool $publishedOnly = true): array
    {
        $posts = [];
        foreach (glob(self::postsDir() . '/*.json') ?: [] as $file) {
            $data = json_decode((string) @file_get_contents($file), true);
            if (!is_array($data) || empty($data['slug'])) continue;
            if ($publishedOnly && ($data['status'] ?? 'draft') !== 'published') continue;
            $posts[] = $data;
        }
        usort($posts, static fn(array $a, array $b) => [$b['date'] ?? '', $b['updatedAt'] ?? ''] <=> [$a['date'] ?? '', $a['updatedAt'] ?? '']);

        return $posts;
    }

    public static function find(string $slug): ?array
    {
        if (!self::validSlug($slug)) return null;

        $file = self::postsDir() . '/' . $slug . '.json';
        if (!is_file($file)) return null;

        $data = json_decode((string) @file_get_contents($file), true);
        return is_array($data) && !empty($data['slug']) ? $data : null;
    }

    public static function save(array $post): bool
    {
        if (!self::validSlug($post['slug'] ?? '')) return false;
        if (!is_dir(self::postsDir()) && !@mkdir(self::postsDir(), 0775, true)) return false;

        // Write to a temporary file first so a half-written post can never replace a good one.
        $file = self::postsDir() . '/' . $post['slug'] . '.json';
        $temp = $file . '.' . bin2hex(random_bytes(4)) . '.tmp';
        $json = json_encode($post, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        if ($json === false || @file_put_contents($temp, $json, LOCK_EX) === false) return false;

        return @rename($temp, $file);
    }

    public static function delete(string $slug): bool
    {
        return self::validSlug($slug) && @unlink(self::postsDir() . '/' . $slug . '.json');
    }

    public static function validSlug(string $slug): bool
    {
        return preg_match('/^[a-z0-9][a-z0-9-]{1,79}$/', $slug) === 1;
    }

    public static function slugify(string $text): string
    {
        $text = str_replace(['’', "'"], '', mb_strtolower(trim($text), 'UTF-8'));
        $text = preg_replace('/[^a-z0-9]+/u', '-', $text) ?? '';

        return substr(trim($text, '-'), 0, 60);
    }

    /** A slug no static page or other post is already using. */
    public static function uniqueSlug(string $wanted, string $currentSlug = ''): string
    {
        $base = self::slugify($wanted) ?: 'post';
        $slug = $base;
        for ($n = 2; self::isTaken($slug, $currentSlug); $n++) {
            $slug = substr($base, 0, 70) . '-' . $n;
        }

        return $slug;
    }

    /** A slug is taken by another post, or by a built guide with the same address. */
    public static function isTaken(string $slug, string $currentSlug = ''): bool
    {
        if ($slug === $currentSlug) return false;
        if (is_file(self::root() . '/blog/' . $slug . '.html')) return true;

        return is_file(self::postsDir() . '/' . $slug . '.json');
    }
}
